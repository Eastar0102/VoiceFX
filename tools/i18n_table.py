OUT = Path(__file__).resolve().parent.parent / "voicefx" / "locales"


def main():
    seen = {}
    for row in ROWS:
        if row[0] in seen and seen[row[0]] != row:
            raise SystemExit(f"원문 중복(번역이 다름): {row[0]}")
        seen[row[0]] = row
    OUT.mkdir(exist_ok=True)
    for i, lang in enumerate(("en", "ja", "zh"), start=1):
        table = {row[0]: row[i] for row in ROWS}
        (OUT / f"{lang}.json").write_text(json.dumps(table, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"{lang}: {len(table)}")


if __name__ == "__main__":
    main()
